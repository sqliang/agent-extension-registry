import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import * as tar from "tar";
import { Installer, LocalRegistry, sha256 } from "../packages/core/dist/index.js";

const root = resolve(process.cwd());
const output = join(root, "dist");
const registry = new LocalRegistry(root);
await registry.load();
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

const items = await registry.list({ includeDeprecated: true });
const catalogItems = [];
for (const item of items) {
  if (item.kind === "plugin" || item.kind === "profile") {
    catalogItems.push({ kind: item.kind, ...item.manifest });
    continue;
  }
  const archiveName = `${item.manifest.id}-v${item.manifest.version}.tar.gz`;
  const archiveDirectory = join(output, "components", item.manifest.id, item.manifest.version);
  const archivePath = join(archiveDirectory, archiveName);
  await mkdir(archiveDirectory, { recursive: true });
  await tar.c({ cwd: item.directory, file: archivePath, gzip: true, portable: true, noMtime: true }, ["."]);
  const digest = sha256(await readFile(archivePath));
  const tag = encodeURIComponent(`component/${item.manifest.id}/v${item.manifest.version}`);
  catalogItems.push({
    kind: item.kind,
    ...item.manifest,
    artifact: {
      url: `https://github.com/sqliang/agent-extension-registry/releases/download/${tag}/${archiveName}`,
      sha256: digest
    }
  });
  await writeFile(`${archivePath}.sha256`, `${digest}  ${archiveName}\n`);
}
const catalog = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),
  repository: "https://github.com/sqliang/agent-extension-registry",
  items: catalogItems
};
await writeFile(join(output, "catalog.json"), `${JSON.stringify(catalog, null, 2)}\n`);

const installer = new Installer(registry);
const bundleItems = items.filter((item) => item.kind === "plugin" || item.kind === "profile");
for (const item of bundleItems) {
  for (const target of ["codex", "claude", "cursor"]) {
    const bundleRoot = join(output, "projections", item.kind, item.manifest.id, item.manifest.version, target);
    await installer.install(`${item.kind}:${item.manifest.id}@${item.manifest.version}`, { root: bundleRoot, targets: [target] });
    await rm(join(bundleRoot, ".agent-ext"), { recursive: true, force: true });
    await rm(join(bundleRoot, "agent-ext.lock.json"), { force: true });

    const portableManifest = {
      name: item.manifest.id,
      version: item.manifest.version,
      description: item.manifest.description
    };
    await writeFile(join(bundleRoot, "plugin.json"), `${JSON.stringify(portableManifest, null, 2)}\n`);
    const compatibility = target === "codex" ? ".codex-plugin" : target === "claude" ? ".claude-plugin" : ".cursor-plugin";
    await mkdir(join(bundleRoot, compatibility), { recursive: true });
    const compatibilityManifest = target === "codex" ? {
      ...portableManifest,
      author: { name: "sqliang", url: "https://github.com/sqliang" },
      homepage: "https://github.com/sqliang/agent-extension-registry",
      repository: "https://github.com/sqliang/agent-extension-registry",
      license: "MIT",
      skills: "./skills/",
      interface: {
        displayName: item.manifest.id.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" "),
        shortDescription: item.manifest.description,
        longDescription: item.manifest.description,
        developerName: "sqliang",
        category: "Developer Tools",
        capabilities: ["Skills"],
        websiteURL: "https://github.com/sqliang/agent-extension-registry",
        defaultPrompt: [`Use the ${item.manifest.id} workflows for this task.`]
      }
    } : target === "claude" ? {
      ...portableManifest,
      author: { name: "sqliang", url: "https://github.com/sqliang" },
      homepage: "https://github.com/sqliang/agent-extension-registry",
      repository: "https://github.com/sqliang/agent-extension-registry",
      license: "MIT"
    } : portableManifest;
    await writeFile(join(bundleRoot, compatibility, "plugin.json"), `${JSON.stringify(compatibilityManifest, null, 2)}\n`);

    const projectSkillRoot = target === "codex" ? join(bundleRoot, ".agents", "skills") : join(bundleRoot, `.${target}`, "skills");
    try {
      await mkdir(join(bundleRoot, "skills"), { recursive: true });
      for (const skill of await readdir(projectSkillRoot)) {
        await cp(join(projectSkillRoot, skill), join(bundleRoot, "skills", skill), { recursive: true });
      }
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
}

await writeFile(join(output, "README.md"), "# Generated output\n\nThis directory is generated by `pnpm build` and must not be committed.\n");
